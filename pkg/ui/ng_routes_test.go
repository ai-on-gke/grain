// ngRoutesFile is the Angular UI's copy of this server's route table
// (design/design/angular-ui.design.md, "Typed API client"): every
// "METHOD /path" the mux serves and the role scope each one needs, read
// off Server.Routes and RoleScopeOf -- the same table the server checks a
// call against -- so the new UI's typed client and its role-aware
// buttons cannot name a route that does not exist or guess a scope the
// server does not ask for.
const ngRoutesFile = "../../ui-ng/src/app/api/generated-routes.ts"

// TestAngularRouteTableInSync fails when the route table changes and the
// generated file was not regenerated. Regenerate it with
//
//	GRAIN_UPDATE_NG_ROUTES=1 go test ./pkg/ui -run TestAngularRouteTableInSync
func TestAngularRouteTableInSync(t *testing.T) {
	srv, _ := testServer(t)
	want := renderNgRoutes(srv.Routes())
	path := filepath.FromSlash(ngRoutesFile)
	if os.Getenv("GRAIN_UPDATE_NG_ROUTES") == "1" {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", ngRoutesFile, err)
	}
	if string(got) != want {
		t.Fatalf("%s is out of date with the server's route table; regenerate it with\n\tGRAIN_UPDATE_NG_ROUTES=1 go test ./pkg/ui -run TestAngularRouteTableInSync", ngRoutesFile)
	}
}

func renderNgRoutes(patterns []string) string {
	var b strings.Builder
	b.WriteString(`// Copyright 2026 Google LLC
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// GENERATED by pkg/ui/ng_routes_test.go from the server's route table.
// Do not edit: regenerate with
//   GRAIN_UPDATE_NG_ROUTES=1 go test ./pkg/ui -run TestAngularRouteTableInSync
//
// scope is the role scope RoleScopeOf says the route needs: "signed-in"
// for any signed-in person, null for a route only a role holding every
// scope (grain/operator) may call.

export const ROUTE_SCOPES = {
`)
	var api []string
	for _, p := range patterns {
		if strings.Contains(p, " /api/") {
			api = append(api, p)
		}
	}
	sort.Strings(api)
	for _, p := range api {
		sc := string(ui.RoleScopeOf(p))
		val := "null"
		if sc != "" {
			val = fmt.Sprintf("%q", sc)
		}
		fmt.Fprintf(&b, "  %q: %s,\n", p, val)
	}
	b.WriteString("} as const;\n\nexport type RouteKey = keyof typeof ROUTE_SCOPES;\n")
	return b.String()
}

//go:build !unix

package cli

import (
	"net"
	"testing"
)

// reserveClosedPort is a loopback port nothing listens on. Off unix the
// port is only closed again, not held, so another process may yet take
// it (closed_port_unix_test.go holds it).
func reserveClosedPort(t *testing.T) string {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	addr := l.Addr().String()
	l.Close()
	return addr
}

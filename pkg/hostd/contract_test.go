package hostd

// The host agent contract's golden test
// (design/design/agentd-stable-contract.design.md, "Guard rails"). Every
// wire type a daemon and a host agent exchange, every allowlist key, op,
// frame, stage operation, dial-out header and login name is rendered into
// one canonical listing, and that listing must equal the block the design
// doc carries between its contract markers. So a change to any of them
// fails CI until the doc changes in the same commit -- which is a path
// .grain/triggers/agentd-contract.yml holds for a person -- and until the
// change names the Feature it ships under (contractFields,
// contractConsts), which must be one this build lists and the doc
// describes in its own row.
//
// Regenerate the block with
//
//	GRAIN_UPDATE_AGENTD_CONTRACT=1 go test ./pkg/hostd -run AgentdContract
//
// which refuses to drop a line the doc already has -- a feature, op,
// frame, field or key a released host agent may depend on -- unless
// GRAIN_AGENTD_CONTRACT_REMOVE=1 says its deprecation window is over.


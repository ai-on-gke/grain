// isContractConst says whether a package-level constant's name makes it
// part of the contract.
func isContractConst(name string) bool {
	switch {
	case strings.HasPrefix(name, "Op") && len(name) > 2,
		strings.HasPrefix(name, "frame"),
		strings.HasPrefix(name, "Stage") && name != "StageRoot",
		strings.HasSuffix(name, "Header"),
		strings.HasPrefix(name, "Login"),
		strings.HasPrefix(name, "Kind"),
		name == "RemotePath", name == "ProbeEnv":
		return true
	}
	return false
}

// contractConstValues parses the package's own (non-test) source for the
// literal value of every contract constant, whatever build tag its file
// carries.
func contractConstValues(t *testing.T) map[string]string {
	t.Helper()
	fset := token.NewFileSet()
	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	out := map[string]string{}
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			for _, spec := range gd.Specs {
				vs := spec.(*ast.ValueSpec)
				for i, n := range vs.Names {
					if !isContractConst(n.Name) || i >= len(vs.Values) {
						continue
					}
					lit, ok := vs.Values[i].(*ast.BasicLit)
					if !ok {
						continue
					}
					out[n.Name] = lit.Value
				}
			}
		}
	}
	return out
}

// renderContract is the canonical listing, one line per item, grouped and
// sorted so that a change shows as a one-line diff.
func renderContract(t *testing.T) (string, []string) {
	t.Helper()
	var problems []string
	known := map[Feature]bool{}
	for _, f := range Features {
		known[f] = true
	}
	var b strings.Builder
	fmt.Fprintf(&b, "protocol_version %d\n", ProtocolVersion)
	fmt.Fprintf(&b, "min_compatible %d\n", MinCompatible)
	for _, f := range Features {
		fmt.Fprintf(&b, "feature %s\n", f)
	}

	listed := map[reflect.Type]bool{}
	for _, ct := range contractTypes {
		listed[reflect.TypeOf(ct.v)] = true
	}
	seen := map[string]bool{}
	for _, ct := range contractTypes {
		rt := reflect.TypeOf(ct.v)
		var lines []string
		for i := 0; i < rt.NumField(); i++ {
			sf := rt.Field(i)
			if !sf.IsExported() {
				continue
			}
			key, _, _ := strings.Cut(sf.Tag.Get(ct.tag), ",")
			if key == "" || key == "-" {
				problems = append(problems, fmt.Sprintf("%s.%s has no %s key: every field of a contract type is named on the wire", rt.Name(), sf.Name, ct.tag))
				continue
			}
			id := rt.Name() + "." + key
			seen[id] = true
			f, ok := contractFields[id]
			switch {
			case !ok:
				problems = append(problems, fmt.Sprintf("%s is new: add it to contractFields with the Feature it ships under (a new one, if an old peer would misread its absence)", id))
			case !known[f]:
				problems = append(problems, fmt.Sprintf("%s ships under feature %q, which Features does not list", id, f))
			}
			ft := sf.Type
			for ft.Kind() == reflect.Pointer || ft.Kind() == reflect.Slice || ft.Kind() == reflect.Map {
				ft = ft.Elem()
			}
			if ft.Kind() == reflect.Struct && ft.PkgPath() == rt.PkgPath() && !listed[ft] {
				problems = append(problems, fmt.Sprintf("%s carries %s, which is not in contractTypes", id, ft.Name()))
			}
			lines = append(lines, fmt.Sprintf("%s %s %s [%s]", ct.tag, id, sf.Type.String(), f))
		}
		b.WriteString(strings.Join(lines, "\n"))
		b.WriteString("\n")
	}
	for id := range contractFields {
		if !seen[id] {
			problems = append(problems, fmt.Sprintf("contractFields names %s, which no contract type has any more", id))
		}
	}

	values := contractConstValues(t)
	names := make([]string, 0, len(values))
	for n := range values {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		f, ok := contractConsts[n]
		switch {
		case !ok:
			problems = append(problems, fmt.Sprintf("constant %s is new: add it to contractConsts with the Feature it ships under", n))
		case !known[f]:
			problems = append(problems, fmt.Sprintf("constant %s ships under feature %q, which Features does not list", n, f))
		}
		fmt.Fprintf(&b, "const %s = %s [%s]\n", n, values[n], f)
	}
	for n := range contractConsts {
		if _, ok := values[n]; !ok {
			problems = append(problems, fmt.Sprintf("contractConsts names %s, which the package no longer declares", n))
		}
	}
	for _, v := range identityEnv {
		fmt.Fprintf(&b, "identity_env %s\n", v)
	}
	for _, v := range envDenyPatterns() {
		fmt.Fprintf(&b, "env_deny %s\n", v)
	}
	fmt.Fprintf(&b, "max_frame %d\n", maxFrame)
	fmt.Fprintf(&b, "max_stage_data %d\n", MaxStageData)
	return b.String(), problems
}

func readContractBlock(t *testing.T) (doc, block string) {
	t.Helper()
	data, err := os.ReadFile(contractDoc)
	if err != nil {
		t.Fatalf("reading the contract doc: %v", err)
	}
	doc = string(data)
	i := strings.Index(doc, contractBegin)
	j := strings.Index(doc, contractEnd)
	if i < 0 || j < i {
		t.Fatalf("%s has no contract block between %q and %q", contractDoc, contractBegin, contractEnd)
	}
	block = doc[i+len(contractBegin) : j]
	block = strings.TrimPrefix(block, "\n```text\n")
	block = strings.TrimSuffix(block, "```\n")
	return doc, block
}

func TestAgentdContractMatchesTheDesignDoc(t *testing.T) {
	got, problems := renderContract(t)
	for _, p := range problems {
		t.Error(p)
	}
	doc, want := readContractBlock(t)

	// Every feature this build lists has a row of its own, written by a
	// person, in the doc's feature table -- the generated block alone
	// would let a feature appear without anyone saying what it promises.
	for _, f := range Features {
		if !strings.Contains(doc, "| `"+string(f)+"` |") {
			t.Errorf("feature %q has no row in %s's feature table (| `%s` | ... |): say what it promises and what a peer without it does", f, contractDoc, f)
		}
	}

	if got == want {
		return
	}
	gotLines := strings.Split(strings.TrimSpace(got), "\n")
	wantLines := strings.Split(strings.TrimSpace(want), "\n")
	var removed, added []string
	for _, l := range wantLines {
		if l != "" && !slices.Contains(gotLines, l) {
			removed = append(removed, l)
		}
	}
	for _, l := range gotLines {
		if !slices.Contains(wantLines, l) {
			added = append(added, l)
		}
	}
	if os.Getenv("GRAIN_UPDATE_AGENTD_CONTRACT") == "" {
		t.Fatalf("the host agent contract changed, and %s does not say so.\n"+
			"A changed wire type, allowlist key, op, frame or header is a contract change: ship it under a feature\n"+
			"(design doc, \"Extensibility rules\"), then regenerate the block with\n"+
			"  GRAIN_UPDATE_AGENTD_CONTRACT=1 go test ./pkg/hostd -run AgentdContract\n"+
			"added:\n  %s\nremoved:\n  %s", contractDoc, strings.Join(added, "\n  "), strings.Join(removed, "\n  "))
	}
	// Lines that only moved (a field's feature re-annotated, say) show
	// as one removed and one added; anything else removed is something a
	// released host agent or daemon may still depend on.
	if len(removed) > 0 && os.Getenv("GRAIN_AGENTD_CONTRACT_REMOVE") == "" {
		t.Fatalf("refusing to drop from the contract what a released peer may depend on (set GRAIN_AGENTD_CONTRACT_REMOVE=1 once its deprecation window is over):\n  %s",
			strings.Join(removed, "\n  "))
	}
	i := strings.Index(doc, contractBegin) + len(contractBegin)
	j := strings.Index(doc, contractEnd)
	updated := doc[:i] + "\n```text\n" + got + "```\n" + doc[j:]
	if err := os.WriteFile(contractDoc, []byte(updated), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("updated %s: added %d line(s), removed %d", contractDoc, len(added), len(removed))
}

// A peer that predates Hello.Features is credited with exactly what its
// protocol version's Supports* gate promised, and nothing that cannot be
// inferred from a version; one that lists features is taken at its word.
func TestHelloHasCreditsLegacyPeersFromTheirProtocol(t *testing.T) {
	cases := []struct {
		h    Hello
		f    Feature
		want bool
	}{
		{legacyHello, FeatureStart, true},
		{legacyHello, FeatureDetach, false},
		{Hello{Protocol: 2}, FeatureDetach, true},
		{Hello{Protocol: 2}, FeatureDrain, true},
		{Hello{Protocol: 2}, FeatureSocketOwner, false},
		{Hello{Protocol: 3}, FeatureSocketOwner, true},
		{Hello{Protocol: 3}, FeatureStage, false},
		{Hello{Protocol: 4}, FeatureStage, true},
		{Hello{Protocol: 4}, FeatureListen, true},
		{Hello{Protocol: 4}, FeatureLogins, false},
		{Hello{Protocol: 4}, FeatureFeatures, false},
		{Hello{Protocol: 4}, FeatureHookPolicy, false},
		{Hello{Protocol: 4, Features: []Feature{FeatureStart, FeatureFeatures}}, FeatureDetach, false},
		{Hello{Protocol: 4, Features: []Feature{FeatureStart, "some_future_feature"}}, "some_future_feature", true},
		{ThisHello("x"), FeatureLogins, true},
		{ThisHello("x"), FeatureHookPolicy, true},
	}
	for _, c := range cases {
		if got := c.h.Has(c.f); got != c.want {
			t.Errorf("Hello{Protocol: %d, Features: %v}.Has(%q) = %v, want %v", c.h.Protocol, c.h.Features, c.f, got, c.want)
		}
	}
	if !ThisHello("x").SupportsCarry() || !(Hello{Protocol: 4}).SupportsCarry() || (Hello{Protocol: 3}).SupportsCarry() {
		t.Error("SupportsCarry must follow stage and listen, from features or protocol")
	}
}

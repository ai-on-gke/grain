// The fixture is generated by TestGateChecksOrdinaryAPIEventsAndNoninterference.
import fs from "node:fs";
import { test, expect } from "./fixtures.js";
const observation = JSON.parse(
  fs.readFileSync(
    new URL("./fixtures/gate-check-observations.json", import.meta.url),
    "utf8",
  ),
);
test("shows scoped current and legacy shadow CI without action controls @phone @dark", async ({
  page,
  axe,
}) => {
  const tasks = await (await page.request.get("/api/tasks")).json();
  const task =
    tasks.find((t: { state: string }) => t.state !== "closed") ?? tasks[0];
  await page.route(`**/api/tasks/${task.id}*`, async (route) => {
    const response = await route.fetch();
    const body = await response.json();
    await route.fulfill({
      response,
      json: { ...body, gate_observations: observation },
    });
  });
  await page.goto(`/next/tasks/${task.id}`);
  const card = page.getByTestId("gate-observations");
  await expect(card).toContainText(
    "Shadow CI prediction · Current CI policy · acme/widgets · pr 7",
  );
  await expect(card).toContainText("Shadow CI prediction · Legacy CI import");
  await expect(card).toContainText("Legacy services remain authoritative");
  await expect(card).toContainText("Prediction only: automatic merge");
  await expect(card.locator("button,a,input")).toHaveCount(0);
  expect(await axe()).toEqual([]);
  const box = await card.boundingBox();
  expect(box!.x + box!.width).toBeLessThanOrEqual(
    page.viewportSize()!.width + 1,
  );
  const dir = process.env["GRAIN_UI_SHOTS"];
  if (dir) {
    fs.mkdirSync(dir, { recursive: true });
    await page.screenshot({
      path: `${dir}/gate-checks-${page.viewportSize()!.width}-${await page.evaluate(() => document.documentElement.dataset["theme"])}.png`,
      fullPage: true,
    });
  }
});
